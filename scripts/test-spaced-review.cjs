"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const ts = require(path.join(__dirname, "..", "node_modules", "typescript"));
const source = fs.readFileSync(path.join(__dirname, "..", "app/_lib/spacedReview.ts"), "utf8");
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const mod = { exports: {} };
new Function("exports", "module", js)(mod.exports, mod);
const { nextReview, dueCards, reviewCardKey, parseReviewSchedule } = mod.exports;
const now = 10000000;
const card = { front: "What is 1/2?", back: "Two quarters" };
const key = reviewCardKey(card);
assert.equal(key, reviewCardKey({ ...card }));
assert.notEqual(key, reviewCardKey({ front: "What is 1/3?", back: "One third" }));
const again = nextReview(undefined, "again", now);
assert.equal(again.dueAt, now + 600000);
assert.equal(again.repetitions, 0);
const first = nextReview(undefined, "got-it", now);
assert.equal(first.dueAt, now + 86400000);
assert.equal(first.repetitions, 1);
const second = nextReview(first, "got-it", first.dueAt);
assert.equal(second.intervalDays, 3);
const queue = dueCards([card], { [key]: first }, now);
assert.equal(queue.length, 0);
assert.equal(dueCards([card], { [key]: first }, first.dueAt).length, 1);
assert.equal(parseReviewSchedule("not-json")[key], undefined);
assert.equal(parseReviewSchedule(JSON.stringify({ [key]: first }))[key].dueAt, first.dueAt);
assert.equal(parseReviewSchedule(JSON.stringify({ bad: { dueAt: NaN } }))[key], undefined);
console.log("PASS: spaced-review scheduling, persistence parsing, and card isolation.");
