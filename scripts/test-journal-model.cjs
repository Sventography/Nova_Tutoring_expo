'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const cache = new Map();
function load(filename) {
  if (cache.has(filename)) return cache.get(filename);
  const exports = {};
  const output = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022},reportDiagnostics:true});
  assert.equal(output.diagnostics.length,0,filename);
  new Function('exports','require',output.outputText)(exports,name=>{
    if(name==='@react-native-async-storage/async-storage') return {default:{}};
    return load(path.resolve(path.dirname(filename),name+'.ts'));
  });
  cache.set(filename,exports);
  return exports;
}
const m=load(path.join(root,'app/_lib/journalModel.ts'));
const state={entryNoteDiscovered:false,seventeenthStarDiscovered:false,nvDiscovered:false,whiteRabbitDiscovered:false,focusPracticeNoteDiscovered:false,libraryNotebookDiscovered:false,lanternFolderDiscovered:false,argAct1Complete:false};
const flags={introduced:false,pencilTraceRead:false,lanternTraceRead:false,copyUnlocked:false,copyRead:false,draftRestored:false,completed:false};
const recovered=()=>m.recoveredNotes(state,flags);
assert.deepEqual(recovered(),[]);
flags.pencilTraceRead=true;
assert.deepEqual(recovered().map(n=>n.id),['pencil']);
assert.equal(m.recoveredHeading(recovered()),'Retained Notes');
state.entryNoteDiscovered=true;
assert.ok(recovered().some(n=>n.id==='garden'));
assert.ok(!recovered().some(n=>n.id==='chart'));
flags.completed=true; flags.draftRestored=true;
assert.ok(!recovered().some(n=>n.id==='session'),'stray flags cannot spoil ending');
flags.completed=false; flags.draftRestored=false;
Object.assign(state,{seventeenthStarDiscovered:true,nvDiscovered:true,whiteRabbitDiscovered:true,focusPracticeNoteDiscovered:true,libraryNotebookDiscovered:true,lanternFolderDiscovered:true});
flags.copyUnlocked=true;
assert.ok(recovered().some(n=>n.id==='folder'));
assert.ok(!recovered().some(n=>n.id==='relay'));
flags.copyRead=true;
assert.ok(recovered().some(n=>n.id==='relay'));
assert.ok(!recovered().some(n=>n.id==='draft'));
flags.draftRestored=true;
assert.ok(recovered().some(n=>n.id==='draft'));
assert.equal(m.recoveredHeading(recovered()),'Retained Notes');
flags.completed=true; state.argAct1Complete=true;
assert.equal(m.recoveredHeading(recovered()),'Nora’s Notes');
assert.ok(recovered().some(n=>n.id==='handwriting'));
assert.equal(new Set(recovered().map(n=>n.id)).size,recovered().length);
assert.notEqual(m.journalStorageKey('a'),m.journalStorageKey('b'));
assert.notEqual(m.journalStorageKey('a'),m.journalStorageKey(null));
const a=m.makeJournalNote('Biology','Cell division','Science'),b=m.makeJournalNote('History');
b.pinned=true;
assert.deepEqual(m.matchingNotes([a,b],'').map(n=>n.title),['History','Biology']);
assert.deepEqual(m.matchingNotes([a,b],'science').map(n=>n.title),['Biology']);
assert.ok(!m.noteHtml({title:'<script>',body:'<img src=x onerror=alert(1)>'}).includes('<script>'));
assert.ok(m.noteHtml({title:'<script>',body:'x'}).includes('&lt;script&gt;'));
console.log('PASS: recovered-note gates, late heading, unique records, account keys, search, pinning, HTML escaping.');
