"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const ts = require(path.join(__dirname, "..", "node_modules", "typescript"));
const source = fs.readFileSync(path.join(__dirname, "..", "app/_lib/argEvidenceTrail.ts"), "utf8");
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const mod = { exports: {} };
new Function("exports", "module", js)(mod.exports, mod);
const build = mod.exports.getArgEvidenceTrail;
const base = { entryNoteDiscovered: false, seventeenthStarDiscovered: false, nvDiscovered: false, whiteRabbitDiscovered: false, focusPracticeNoteDiscovered: false, libraryNotebookDiscovered: false, lanternCopyDiscovered: false, lanternFolderDiscovered: false, argAct1Complete: false };
const flags = { introduced: false, copyUnlocked: false, copyRead: false, draftRestored: false, completed: false };
assert.equal(build(base, flags).found.length, 0, "ordinary tutoring gets no spoilers");
const keys = ["entryNoteDiscovered", "seventeenthStarDiscovered", "nvDiscovered", "whiteRabbitDiscovered", "focusPracticeNoteDiscovered", "libraryNotebookDiscovered", "lanternCopyDiscovered", "lanternFolderDiscovered"];
let state = { ...base };
keys.forEach((key, i) => {
  state = { ...state, [key]: true };
  const route = build(state, flags);
  assert.equal(route.found.length, i + 1);
  assert.ok(route.nextQuestion.length > 10);
  assert.ok(route.nextNudge);
  if (i !== keys.length - 1) assert.equal(route.completed, false);
});
state.argAct1Complete = true; // A legacy file checkpoint survives the update.
assert.equal(build(state, flags).completed, false);
flags.copyUnlocked = true;
assert.match(build(state, flags).nextNudge, /Field Notes/);
flags.copyRead = true;
assert.equal(build(state, flags).found.at(-1).id, "field-notes");
assert.equal(build(state, flags).found.some(item => item.id === "preserved"), false);
flags.draftRestored = true;
assert.equal(build(state, flags).found.at(-1).id, "preserved");
assert.equal(build(state, flags).completed, false);
flags.completed = true;
assert.equal(build(state, flags).found.at(-1).id, "session");
assert.equal(build(state, flags).completed, true);
assert.ok(build(base, {}).found.every(x => !x.observation.includes("QUIET")));
console.log("PASS: evidence records accumulate without spoiling future discoveries.");
